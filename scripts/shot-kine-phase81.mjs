import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
const srv = spawn('npm', ['run', 'dev', '--', '--host', '127.0.0.1'], { cwd: process.cwd(), stdio: 'ignore', detached: true });
await new Promise((r) => setTimeout(r, 4000));
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto('http://127.0.0.1:5173/');
await page.locator('.module-list-item', { hasText: 'Movement Theater' }).click();
await page.waitForSelector('.kine-stage canvas', { timeout: 20000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: 'docs/screenshots/shot-kine-phase81-honesty-ticks.png' });
await page.waitForTimeout(1200);
await page.screenshot({ path: 'docs/screenshots/shot-kine-phase82-angles.png', clip: { x: 1060, y: 0, width: 380, height: 1000 } });
await page.locator('.kine-legend-row').first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'docs/screenshots/shot-kine-phase83-pins-spark.png', clip: { x: 0, y: 300, width: 1440, height: 700 } });
await browser.close();
process.kill(-srv.pid);
process.exit(0);

import assert from 'node:assert/strict';
import { anatomyRegistry, ANATOMY_REGISTRY_VERSION, getAnatomyReference, getRegistrySummary, validateAnatomyRegistry } from '../src/data/anatomyRegistry.js';
import { readFile } from 'node:fs/promises';
import { validateConceptualSourceReview } from '../src/data/learningSources.js';

const errors = validateAnatomyRegistry();
assert.deepEqual(errors, [], `Anatomy registry errors: ${errors.join('; ')}`);
assert.deepEqual(validateConceptualSourceReview(), [], 'Conceptual source review errors detected');
assert.equal(ANATOMY_REGISTRY_VERSION, 2);
assert.ok(Object.keys(anatomyRegistry).length >= 8);
for (const id of ['heart-macro', 'digestive-macro', 'respiratory-macro', 'kidney-macro', 'nervous-macro', 'reproductive-macro']) {
  assert.deepEqual(anatomyRegistry[id].viewPresets, ['anterior', 'lateral', 'posterior']);
}
assert.equal(getAnatomyReference('heart-macro').source.license, 'CC BY 4.0');
assert.equal(getAnatomyReference('alveoli-teaching').representation, 'simplified-teaching');
assert.ok(getRegistrySummary().sourceReferences >= 6);
assert.ok(getRegistrySummary().simplifiedTeaching >= 2);

const referenceObject = await readFile('src/components/ReferenceObject3D.jsx', 'utf8');
const guidedPaths = await readFile('src/data/guidedPaths.js', 'utf8');
const circulation = await readFile('src/simulations/CirculationLab.jsx', 'utf8');
const digestion = await readFile('src/simulations/DigestiveLab.jsx', 'utf8');
const sceneManager = await readFile('src/lib/AnatomySceneManager.js', 'utf8');
assert.match(referenceObject, /getAnatomyReference/);
assert.match(referenceObject, /Representation:/);
assert.match(referenceObject, /teachingOverlay/);
assert.match(guidedPaths, /getAnatomyReference/);
assert.match(circulation, /registryId="heart-macro"/);
assert.match(circulation, /circulation-route-state/);
assert.match(circulation, /circulationTeachingStages/);
assert.match(circulation, /circulation-pressure-state/);
assert.match(circulation, /pressureMarkers/);
assert.match(circulation, /circulation-live-reference/);
assert.match(circulation, /createLiveCardioOverlay/);
const cardioEngine = await readFile('src/lib/CardioPhysiologyEngine.js', 'utf8');
assert.match(cardioEngine, /valveGradients/);
assert.match(sceneManager, /createExactSelectionGeometry/);
assert.match(sceneManager, /teachingOverlayStructureKey/);
assert.match(sceneManager, /updateTeachingOverlayMarkers/);
assert.match(sceneManager, /teachingGradient/);
const overlayQc = await readFile('scripts/teaching-overlay-qc.mjs', 'utf8');
assert.match(overlayQc, /source anchors/);
const learningSources = await readFile('src/data/learningSources.js', 'utf8');
const sourceNote = await readFile('src/components/ConceptualSourceNote.jsx', 'utf8');
assert.match(learningSources, /CONCEPTUAL_SOURCE_REVIEW/);
assert.match(learningSources, /No reviewed 3D source approved/);
assert.match(sourceNote, /REVIEWED CONCEPTUAL SOURCE/);
const visualReview = await readFile('scripts/visual-review-gate.mjs', 'utf8');
const visualStatus = await readFile('scripts/visual-review-status.json', 'utf8');
assert.match(visualReview, /--strict/);
assert.match(visualStatus, /"status": "pending"/);
const sourceCandidates = await readFile('scripts/3d-source-candidate-report.mjs', 'utf8');
const sourceCandidateStatus = await readFile('scripts/3d-source-candidates.json', 'utf8');
assert.match(sourceCandidates, /none approved/);
assert.match(sourceCandidateStatus, /candidate-not-approved/);
const releaseReadiness = await readFile('scripts/release-readiness.mjs', 'utf8');
assert.match(releaseReadiness, /--strict/);
const overlaySpec = await readFile('src/data/teachingOverlaySpec.js', 'utf8');
assert.match(overlaySpec, /TEACHING_OVERLAY_SPEC/);
const cardioSmoke = await readFile('scripts/cardio-physics-smoke.mjs', 'utf8');
assert.match(cardioSmoke, /valveGradients/);
assert.match(sceneManager, /exact group geometry|selected valve/);
assert.match(digestion, /registryId="digestive-macro"/);
assert.match(digestion, /digestion-structure-state/);
assert.match(digestion, /digestiveTeachingStages/);
assert.match(sceneManager, /setTeachingOverlay/);
assert.match(sceneManager, /getTeachingAnchor/);

console.log(`Anatomy registry smoke passed (${Object.keys(anatomyRegistry).length} entries)`);
